    const rtlLanguages = ["fa", "ps", "ar", "ur", "he"];
    let currentLanguage = "en";

    function translate(key) {
        const currentDictionary = dictionaries[currentLanguage] || dictionaries.en;
        const supplemental = supplementalDictionaries[currentLanguage] || {};
        const supplementalEnglish = supplementalDictionaries.en || {};
        return supplemental[key] || currentDictionary[key] || supplementalEnglish[key] || dictionaries.en[key] || key;
    }

    function applyInterfaceLanguage(language) {
        currentLanguage = dictionaries[language] ? language : "en";
        document.documentElement.lang = currentLanguage;
        document.documentElement.dir = rtlLanguages.includes(currentLanguage) ? "rtl" : "ltr";

        document.querySelectorAll("[data-i18n]").forEach((element) => {
            const key = element.dataset.i18n;
            const translated = translate(key);

            if (translated) {
                element.textContent = translated;
            }
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
            const key = element.dataset.i18nPlaceholder;
            element.placeholder = translate(key);
        });

        document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
            const key = element.dataset.i18nAria;
            element.setAttribute("aria-label", translate(key));
            element.title = translate(key);
        });
    }

    window.VoiceFlowI18n = {
        translate,
        applyInterfaceLanguage,
        isRtlLanguage(language) {
            return rtlLanguages.includes(language);
        }
    };
